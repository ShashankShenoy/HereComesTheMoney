WITH DERIVED AS (
  SELECT
      P.BANK_ACCOUNT_ID,
      P.CURRENCY_CODE,
      SUM(CASE WHEN P.ENTRY_SIDE = 'CR' THEN P.AMOUNT ELSE -P.AMOUNT END) AS GL_DERIVED_BALANCE
  FROM M05_GL_POSTING P
  WHERE P.BANK_ACCOUNT_ID IS NOT NULL
  GROUP BY P.BANK_ACCOUNT_ID, P.CURRENCY_CODE
)
SELECT
    A.BANK_ACCOUNT_ID,
    A.CURRENCY_CODE,
    A.POSTED_BALANCE,
    NVL(D.GL_DERIVED_BALANCE, 0) AS GL_DERIVED_BALANCE,
    A.POSTED_BALANCE - NVL(D.GL_DERIVED_BALANCE, 0) AS DIFFERENCE,
    CASE WHEN A.POSTED_BALANCE = NVL(D.GL_DERIVED_BALANCE, 0) THEN 'Y' ELSE 'N' END AS IS_MATCHED,
    A.AS_OF
FROM M05_ACCOUNT_POSITION A
LEFT JOIN DERIVED D
  ON D.BANK_ACCOUNT_ID = A.BANK_ACCOUNT_ID
 AND D.CURRENCY_CODE = A.CURRENCY_CODE;

CREATE VIEW M05_V_LOAN_RECEIVABLE_POSITION AS
SELECT
    P.LOAN_FACILITY_ID,
    P.LOAN_COMPONENT_CODE,
    P.CURRENCY_CODE,
    SUM(CASE WHEN P.ENTRY_SIDE = 'DR' THEN P.AMOUNT ELSE -P.AMOUNT END) AS RECEIVABLE_BALANCE,
    MAX(J.BOOKED_AT) AS AS_OF
FROM M05_GL_POSTING P
JOIN M05_GL_JOURNAL J ON J.JOURNAL_ID = P.JOURNAL_ID
WHERE P.LOAN_FACILITY_ID IS NOT NULL
GROUP BY P.LOAN_FACILITY_ID, P.LOAN_COMPONENT_CODE, P.CURRENCY_CODE;

CREATE VIEW M08_V_PAYMENT_ALLOCATION_CONTROL AS
SELECT
    P.LOAN_PAYMENT_ID,
    P.FACILITY_ID,
    P.AMOUNT AS PAYMENT_AMOUNT,
    NVL(SUM(A.AMOUNT), 0) AS ALLOCATED_AMOUNT,
    P.AMOUNT - NVL(SUM(A.AMOUNT), 0) AS UNALLOCATED_AMOUNT,
    CASE WHEN P.AMOUNT = NVL(SUM(A.AMOUNT), 0) THEN 'Y' ELSE 'N' END AS IS_FULLY_ALLOCATED
FROM M08_LOAN_PAYMENT P
LEFT JOIN M08_LOAN_PAYMENT_ALLOCATION A
  ON A.LOAN_PAYMENT_ID = P.LOAN_PAYMENT_ID
GROUP BY P.LOAN_PAYMENT_ID, P.FACILITY_ID, P.AMOUNT;

CREATE VIEW M08_V_SCHEDULE_TOTAL_CONTROL AS
SELECT
    S.SCHEDULE_ID,
    S.FACILITY_ID,
    S.TOTAL_PRINCIPAL,
    S.TOTAL_INTEREST,
    S.TOTAL_FEES,
    NVL(SUM(I.PRINCIPAL_DUE), 0) AS ITEM_PRINCIPAL,
    NVL(SUM(I.INTEREST_DUE), 0) AS ITEM_INTEREST,
    NVL(SUM(I.FEE_DUE), 0) AS ITEM_FEES,
    CASE
      WHEN S.TOTAL_PRINCIPAL = NVL(SUM(I.PRINCIPAL_DUE), 0)
       AND S.TOTAL_INTEREST = NVL(SUM(I.INTEREST_DUE), 0)
       AND S.TOTAL_FEES = NVL(SUM(I.FEE_DUE), 0)
      THEN 'Y' ELSE 'N'
    END AS IS_MATCHED
FROM M08_LOAN_SCHEDULE S
LEFT JOIN M08_LOAN_SCHEDULE_ITEM I ON I.SCHEDULE_ID = S.SCHEDULE_ID
GROUP BY S.SCHEDULE_ID, S.FACILITY_ID,
         S.TOTAL_PRINCIPAL, S.TOTAL_INTEREST, S.TOTAL_FEES;

CREATE VIEW M08_V_DISBURSEMENT_CONTROL AS
SELECT
    F.FACILITY_ID,
    F.PRINCIPAL_AMOUNT,
    F.TOTAL_DISBURSED_AMOUNT,
    NVL(SUM(CASE WHEN D.STATUS = 'POSTED' THEN D.AMOUNT ELSE 0 END), 0) AS POSTED_DISBURSEMENTS,
    F.TOTAL_DISBURSED_AMOUNT
      - NVL(SUM(CASE WHEN D.STATUS = 'POSTED' THEN D.AMOUNT ELSE 0 END), 0) AS DIFFERENCE,
    CASE
      WHEN F.TOTAL_DISBURSED_AMOUNT
        = NVL(SUM(CASE WHEN D.STATUS = 'POSTED' THEN D.AMOUNT ELSE 0 END), 0)
      THEN 'Y' ELSE 'N'
    END AS IS_MATCHED
FROM M08_LOAN_FACILITY F
LEFT JOIN M08_LOAN_DISBURSEMENT D ON D.FACILITY_ID = F.FACILITY_ID
GROUP BY F.FACILITY_ID, F.PRINCIPAL_AMOUNT, F.TOTAL_DISBURSED_AMOUNT;

CREATE VIEW M07_V_RESERVE_POSITION_RECON AS
WITH DERIVED AS (
  SELECT
      RESERVE_ACCOUNT_ID,
      CURRENCY_CODE,
      SUM(CASE WHEN MOVEMENT_SIDE = 'IN' THEN AMOUNT ELSE -AMOUNT END) AS LEDGER_BALANCE
  FROM M07_CENTRAL_TREASURY_LEDGER
  GROUP BY RESERVE_ACCOUNT_ID, CURRENCY_CODE
)
SELECT
    P.RESERVE_ACCOUNT_ID,
    P.CURRENCY_CODE,
    P.CONFIRMED_BALANCE,
    NVL(D.LEDGER_BALANCE, 0) AS LEDGER_BALANCE,
    P.CONFIRMED_BALANCE - NVL(D.LEDGER_BALANCE, 0) AS DIFFERENCE,
    CASE WHEN P.CONFIRMED_BALANCE = NVL(D.LEDGER_BALANCE, 0) THEN 'Y' ELSE 'N' END AS IS_MATCHED,
    P.AS_OF
FROM M07_RESERVE_POSITION P
LEFT JOIN DERIVED D
  ON D.RESERVE_ACCOUNT_ID = P.RESERVE_ACCOUNT_ID
 AND D.CURRENCY_CODE = P.CURRENCY_CODE;