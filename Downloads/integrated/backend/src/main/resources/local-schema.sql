CREATE VIEW M05_V_GL_JOURNAL_CONTROL AS
SELECT
    J.JOURNAL_ID,
    J.CURRENCY_CODE,
    COUNT(P.POSTING_ID) AS LINE_COUNT,
    NVL(SUM(CASE WHEN P.ENTRY_SIDE = 'DR' THEN P.AMOUNT ELSE 0 END), 0) AS DEBIT_TOTAL,
    NVL(SUM(CASE WHEN P.ENTRY_SIDE = 'CR' THEN P.AMOUNT ELSE 0 END), 0) AS CREDIT_TOTAL,
    NVL(SUM(CASE WHEN P.ENTRY_SIDE = 'DR' THEN P.AMOUNT ELSE -P.AMOUNT END), 0) AS BALANCE_DIFFERENCE,
    CASE
      WHEN COUNT(P.POSTING_ID) >= 2
       AND NVL(SUM(CASE WHEN P.ENTRY_SIDE = 'DR' THEN P.AMOUNT ELSE -P.AMOUNT END), 0) = 0
      THEN 'Y' ELSE 'N'
    END AS IS_BALANCED
FROM M05_GL_JOURNAL J
LEFT JOIN M05_GL_POSTING P ON P.JOURNAL_ID = J.JOURNAL_ID
GROUP BY J.JOURNAL_ID, J.CURRENCY_CODE;

