/** Returns a localized UI phrase and falls back to the English source. */
export function t(source) {
  const value = String(source ?? '');
  if (locale === 'en-IN') return value;
  const match = /^(\s*)(.*?)(\s*)$/s.exec(value);
  const core=match[2];
  const translated = (catalog[core] || normalizedCatalog[core.toLocaleLowerCase('en')])?.[locale];
  if (translated) return match[1] + translated + match[3];
  const count=/^(\d+) (available|records? shown)$/.exec(core);
  if (count) return match[1]+count[1]+' '+(count[2]==='available'?t('available'):t(count[2].split(' ')[0])+' '+t('shown'))+match[3];
  const open=/^Open (.+) →$/.exec(core);
  if (open) return match[1]+(locale==='hi-IN'?`${t(open[1])} खोलें →`:`${t(open[1])} ತೆರೆಯಿರಿ →`)+match[3];
  return value;
}

/** Translates generated OpenAPI field names when no full-phrase translation exists. */
export function tField(source) {
  const direct=t(source);
  if (direct!==source || locale==='en-IN') return direct;
  const words=String(source).match(/[A-Za-z]+|[^A-Za-z]+/g) || [];
  return words.map(word=>fieldWords[word.toLocaleLowerCase('en')]?.[locale] || word).join('');
}

/** Changes language by reloading JET's locale bundles; API state is left on the server. */
export function setLocale(next) {
  if (!supported.includes(next) || next === locale) return;
  localStorage.setItem(storageKey, next);
  window.location.reload();
}

/** Converts existing and newly inserted UI copy, without changing form values. */
export function localize(root) {
  if (locale === 'en-IN' || !root) return;
  // JET owns its generated input DOM. Labels are translated before enhanceForms() creates it.
  const skip = element => element.closest('script,style,code,pre,textarea,.assistant-markdown,.amount-value,.numeric-value,oj-input-text,oj-input-password,oj-input-date,oj-text-area,oj-select-single');
  const translateNode = node => {
    if (node.nodeType !== Node.TEXT_NODE || !node.parentElement || skip(node.parentElement)) return;
    const next = node.parentElement.closest('label.field,th,dt,legend') ? tField(node.nodeValue) : t(node.nodeValue);
    if (next !== node.nodeValue) node.nodeValue = next;
  };
  if (root.nodeType === Node.TEXT_NODE) translateNode(root);
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) translateNode(walker.currentNode);
  const elements = root.nodeType === Node.ELEMENT_NODE ? [root, ...root.querySelectorAll('*')] : [];
  for (const element of elements) {
    if (skip(element)) continue;
    for (const attr of ['placeholder', 'title', 'aria-label', 'label-hint']) {
      if (element.hasAttribute(attr)) {
        const original = element.getAttribute(attr);
        const next = t(original);
        if (next !== original) element.setAttribute(attr, next);
      }
    }
  }
}

/** Watches the HTML generated by legacy pages and by the assistant widget. */
export function watchTranslations() {
  document.title = t('Moneybags · Banking workspace');
  if (locale === 'en-IN') return;
  localize(document.body);
  new MutationObserver(changes => {
    for (const change of changes) {
      if (change.type === 'characterData') localize(change.target);
      for (const node of change.addedNodes || []) localize(node);
    }
  }).observe(document.body, {subtree: true, childList: true, characterData: true});
}
