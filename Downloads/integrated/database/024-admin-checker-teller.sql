-- Add teller duties to existing bank roles without replacing any other grants.
SET DEFINE OFF
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
DECLARE
  n NUMBER;
BEGIN
  SELECT COUNT(*) INTO n FROM M01_IAM_PERMISSION
    WHERE PERMISSION_CODE IN ('TELLER_READ','TELLER_OPERATE','TELLER_APPROVE','ACCOUNT_READ','TXN_READ','TXN_POST');
  IF n<>6 THEN RAISE_APPLICATION_ERROR(-20096,'Install the teller permission catalog before granting teller access.'); END IF;
  INSERT INTO M01_IAM_ROLE_PERMISSION (ROLE_ID,PERMISSION_ID)
    SELECT r.ROLE_ID,p.PERMISSION_ID FROM M01_IAM_ROLE r CROSS JOIN M01_IAM_PERMISSION p
    WHERE r.ROLE_CODE IN ('BANK_ADMIN','BANK_CHECKER')
      AND p.PERMISSION_CODE IN ('TELLER_READ','TELLER_OPERATE','TELLER_APPROVE','ACCOUNT_READ','TXN_READ','TXN_POST')
      AND NOT EXISTS (SELECT 1 FROM M01_IAM_ROLE_PERMISSION rp WHERE rp.ROLE_ID=r.ROLE_ID AND rp.PERMISSION_ID=p.PERMISSION_ID);
  IF SQL%ROWCOUNT>0 THEN
    UPDATE M01_IAM_USER SET ENTITLEMENT_VERSION=ENTITLEMENT_VERSION+1,ROW_VERSION=ROW_VERSION+1,UPDATED_AT=SYSTIMESTAMP
      WHERE USER_ID IN (SELECT a.USER_ID FROM M01_IAM_USER_ROLE a JOIN M01_IAM_ROLE r ON r.ROLE_ID=a.ROLE_ID
        WHERE r.ROLE_CODE IN ('BANK_ADMIN','BANK_CHECKER') AND a.STATUS='ACTIVE');
    INSERT INTO M01_IAM_AUDIT_EVENT(AUDIT_ID,EVENT_TYPE,RESOURCE_TYPE,RESOURCE_ID,RESULT,REASON_CODE)
      VALUES (LOWER(RAWTOHEX(SYS_GUID())),'TELLER_ACCESS_GRANTED','IAM_ROLE','BANK_ADMIN,BANK_CHECKER','SUCCESS','REQUESTED_TELLER_DUTIES');
  END IF;
END;
/
COMMIT;
