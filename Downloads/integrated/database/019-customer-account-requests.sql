-- Customer limit requests and account issue reports. Run as the application schema owner.
-- Existing M04_ACCOUNT_LIMIT rows remain authoritative; a request never changes a limit.
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

CREATE TABLE MBX_ACCOUNT_CUSTOMER_REQUEST (
  CUSTOMER_REQUEST_ID NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  ACCOUNT_ID NUMBER(19) NOT NULL REFERENCES M04_BANK_ACCOUNT(ACCOUNT_ID),
  REQUEST_ID VARCHAR2(60 CHAR) NOT NULL UNIQUE,
  REQUEST_TYPE VARCHAR2(20 CHAR) NOT NULL,
  OPERATION_CODE VARCHAR2(40 CHAR),
  PERIOD_CODE VARCHAR2(20 CHAR),
  REQUESTED_AMOUNT NUMBER(18,2),
  DETAILS VARCHAR2(500 CHAR) NOT NULL,
  REQUEST_STATUS VARCHAR2(20 CHAR) DEFAULT 'PENDING' NOT NULL,
  REQUESTED_BY_USER_ID VARCHAR2(36 CHAR) NOT NULL,
  REQUESTED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  DECIDED_BY_USER_ID VARCHAR2(36 CHAR),
  DECIDED_AT TIMESTAMP(6) WITH TIME ZONE,
  DECISION_REASON VARCHAR2(500 CHAR),
  APPLIED_LIMIT_ID NUMBER REFERENCES M04_ACCOUNT_LIMIT(LIMIT_ID),
  CONSTRAINT MBX_ACCT_REQ_TYPE CHECK (REQUEST_TYPE IN ('LIMIT_CHANGE','ISSUE')),
  CONSTRAINT MBX_ACCT_REQ_STATUS CHECK (REQUEST_STATUS IN ('PENDING','APPROVED','REJECTED','RESOLVED')),
  CONSTRAINT MBX_ACCT_REQ_LIMIT CHECK (
    (REQUEST_TYPE='LIMIT_CHANGE' AND OPERATION_CODE IS NOT NULL AND PERIOD_CODE IS NOT NULL AND REQUESTED_AMOUNT>0)
    OR (REQUEST_TYPE='ISSUE' AND OPERATION_CODE IS NULL AND PERIOD_CODE IS NULL AND REQUESTED_AMOUNT IS NULL)),
  CONSTRAINT MBX_ACCT_REQ_DECISION CHECK (
    (REQUEST_STATUS='PENDING' AND DECIDED_BY_USER_ID IS NULL AND DECIDED_AT IS NULL)
    OR (REQUEST_STATUS<>'PENDING' AND DECIDED_BY_USER_ID IS NOT NULL AND DECIDED_AT IS NOT NULL)),
  CONSTRAINT MBX_ACCT_REQ_APPLIED CHECK (REQUEST_STATUS<>'APPROVED' OR APPLIED_LIMIT_ID IS NOT NULL),
  CONSTRAINT MBX_ACCT_REQ_SEPARATION CHECK (DECIDED_BY_USER_ID IS NULL OR DECIDED_BY_USER_ID<>REQUESTED_BY_USER_ID)
);
CREATE INDEX MBX_ACCT_REQ_QUEUE ON MBX_ACCOUNT_CUSTOMER_REQUEST(REQUEST_STATUS,REQUESTED_AT);
CREATE INDEX MBX_ACCT_REQ_ACCOUNT ON MBX_ACCOUNT_CUSTOMER_REQUEST(ACCOUNT_ID,REQUESTED_AT);
COMMIT;
