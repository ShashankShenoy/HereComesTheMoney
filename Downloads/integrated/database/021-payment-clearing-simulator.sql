CREATE TABLE MBX_SIM_BANK (
 BANK_CODE VARCHAR2(10) PRIMARY KEY, BANK_NAME VARCHAR2(100) NOT NULL,
 RESERVE_ACCOUNT_ID NUMBER(19), BALANCE NUMBER(18,2) DEFAULT 0 NOT NULL,
 HELD_AMOUNT NUMBER(18,2) DEFAULT 0 NOT NULL,
 CONSTRAINT MBX_SIM_BANK_RESERVE FOREIGN KEY (RESERVE_ACCOUNT_ID) REFERENCES M07_RESERVE_ACCOUNT(RESERVE_ACCOUNT_ID),
 CONSTRAINT MBX_SIM_BANK_AMOUNT CHECK (BALANCE>=0 AND HELD_AMOUNT>=0 AND HELD_AMOUNT<=BALANCE),
 CONSTRAINT MBX_SIM_BANK_OWN CHECK ((BANK_CODE='MCP' AND RESERVE_ACCOUNT_ID IS NOT NULL) OR (BANK_CODE<>'MCP' AND RESERVE_ACCOUNT_ID IS NULL))
);
