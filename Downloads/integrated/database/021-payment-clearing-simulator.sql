CREATE TABLE MBX_SIM_PAYMENT (
 PAYMENT_ID NUMBER(19) PRIMARY KEY REFERENCES M06_PAYMENT_INSTRUCTION(PAYMENT_ID),
 EXTERNAL_REFERENCE VARCHAR2(92) UNIQUE, REQUEST_HASH RAW(32),
 FROM_BANK VARCHAR2(10) NOT NULL, TO_BANK VARCHAR2(10) NOT NULL,
 RESERVE_ACCOUNT_ID NUMBER(19) NOT NULL REFERENCES M07_RESERVE_ACCOUNT(RESERVE_ACCOUNT_ID),
 CUSTOMER_JOURNAL_ID NUMBER(19), SETTLEMENT_REFERENCE VARCHAR2(100),
 SENDER_DETAILS VARCHAR2(300), APPROVED_BY VARCHAR2(100),
 CONSTRAINT MBX_SIM_PAYMENT_FROM FOREIGN KEY (FROM_BANK) REFERENCES MBX_SIM_BANK(BANK_CODE),
 CONSTRAINT MBX_SIM_PAYMENT_TO FOREIGN KEY (TO_BANK) REFERENCES MBX_SIM_BANK(BANK_CODE),
 CONSTRAINT MBX_SIM_PAYMENT_SIDE CHECK ((FROM_BANK='MCP' AND TO_BANK<>'MCP') OR (TO_BANK='MCP' AND FROM_BANK<>'MCP'))
);
CREATE TABLE MBX_SIM_WINDOW (
 SETTLEMENT_CYCLE_ID NUMBER(19) PRIMARY KEY REFERENCES M07_SETTLEMENT_CYCLE(SETTLEMENT_CYCLE_ID),
 CLEARING_BATCH_ID NUMBER(19) NOT NULL UNIQUE REFERENCES M06_CLEARING_BATCH(CLEARING_BATCH_ID),
 WINDOW_START TIMESTAMP(6) WITH TIME ZONE NOT NULL, WINDOW_END TIMESTAMP(6) WITH TIME ZONE NOT NULL,
 CONSTRAINT MBX_SIM_WINDOW_TIMES CHECK (WINDOW_END>WINDOW_START)
);
CREATE TABLE MBX_SIM_SETTLEMENT (
 SETTLEMENT_REFERENCE VARCHAR2(100) PRIMARY KEY, PAYMENT_ID NUMBER(19) UNIQUE REFERENCES M06_PAYMENT_INSTRUCTION(PAYMENT_ID),
 SETTLEMENT_CYCLE_ID NUMBER(19) UNIQUE REFERENCES M07_SETTLEMENT_CYCLE(SETTLEMENT_CYCLE_ID),
 STATUS VARCHAR2(20) NOT NULL, JOURNAL_ID NUMBER(19), TREASURY_ENTRY_ID NUMBER(19),
 CONFIRMED_AT TIMESTAMP(6) WITH TIME ZONE NOT NULL,
 CONSTRAINT MBX_SIM_SETTLEMENT_SCOPE CHECK ((PAYMENT_ID IS NULL AND SETTLEMENT_CYCLE_ID IS NOT NULL) OR (PAYMENT_ID IS NOT NULL AND SETTLEMENT_CYCLE_ID IS NULL)),
 CONSTRAINT MBX_SIM_SETTLEMENT_STATUS CHECK (STATUS='CONFIRMED')
);
CREATE TABLE MBX_SIM_MOVEMENT (
 SETTLEMENT_REFERENCE VARCHAR2(100) NOT NULL REFERENCES MBX_SIM_SETTLEMENT(SETTLEMENT_REFERENCE),
 BANK_CODE VARCHAR2(10) NOT NULL REFERENCES MBX_SIM_BANK(BANK_CODE),
 NET_AMOUNT NUMBER(18,2) NOT NULL, BALANCE_BEFORE NUMBER(18,2) NOT NULL, BALANCE_AFTER NUMBER(18,2) NOT NULL,
 CONSTRAINT MBX_SIM_MOVEMENT_PK PRIMARY KEY (SETTLEMENT_REFERENCE,BANK_CODE),
 CONSTRAINT MBX_SIM_MOVEMENT_BALANCE CHECK (BALANCE_AFTER=BALANCE_BEFORE+NET_AMOUNT AND BALANCE_AFTER>=0)
);
CREATE TABLE MBX_EMPLOYEE_ERROR (
 ERROR_ID VARCHAR2(36) PRIMARY KEY, OCCURRED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
 SERVICE_NAME VARCHAR2(50) NOT NULL, ERROR_CODE VARCHAR2(100) NOT NULL,
 SAFE_MESSAGE VARCHAR2(500) NOT NULL, CORRELATION_ID VARCHAR2(100)
);
