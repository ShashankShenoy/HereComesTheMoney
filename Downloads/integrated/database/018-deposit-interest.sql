-- Run as the application schema owner before deploying deposit-interest code.
-- Review the expense/liability GLs and effective product mappings before use.
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

CREATE TABLE MBX_INTEREST_ROLLOUT (
  CONFIG_ID NUMBER(1) PRIMARY KEY,
  START_DATE DATE NOT NULL,
  CONSTRAINT MBX_INTEREST_ROLLOUT_ONE CHECK (CONFIG_ID=1)
);
INSERT INTO MBX_INTEREST_ROLLOUT(CONFIG_ID,START_DATE) VALUES (1,TRUNC(SYSDATE));

CREATE TABLE MBX_SAVINGS_INTEREST_PERIOD (
  ACCOUNT_ID NUMBER(19) NOT NULL REFERENCES M04_BANK_ACCOUNT(ACCOUNT_ID),
  PERIOD_MONTH DATE NOT NULL,
  INTEREST_AMOUNT NUMBER(18,2) NOT NULL,
  TXN_ID NUMBER(19) REFERENCES M05_TXN_TRANSACTION_LOG(TXN_ID),
  JOURNAL_ID NUMBER(19) REFERENCES M05_GL_JOURNAL(JOURNAL_ID),
  POSTED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  PRIMARY KEY (ACCOUNT_ID,PERIOD_MONTH),
  CONSTRAINT MBX_SAVINGS_INTEREST_AMOUNT CHECK (INTEREST_AMOUNT>=0)
);

CREATE TABLE M03_PM_TERM_DEPOSIT_RULE (
  PRODUCT_VERSION_ID NUMBER PRIMARY KEY REFERENCES M03_PM_PRODUCT_VERSION(PRODUCT_VERSION_ID),
  MIN_DEPOSIT_AMOUNT NUMBER(18,2) NOT NULL,
  MAX_DEPOSIT_AMOUNT NUMBER(18,2) NOT NULL,
  MIN_TENURE_MONTHS NUMBER(4) NOT NULL,
  MAX_TENURE_MONTHS NUMBER(4) NOT NULL,
  CONSTRAINT MBX_TERM_RULE_AMOUNTS CHECK (MIN_DEPOSIT_AMOUNT>0 AND MAX_DEPOSIT_AMOUNT>=MIN_DEPOSIT_AMOUNT),
  CONSTRAINT MBX_TERM_RULE_TERMS CHECK (MIN_TENURE_MONTHS>0 AND MAX_TENURE_MONTHS>=MIN_TENURE_MONTHS)
);

CREATE TABLE MBX_TERM_DEPOSIT (
  TERM_DEPOSIT_ID NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  REQUEST_KEY VARCHAR2(120 CHAR) NOT NULL UNIQUE,
  PRIMARY_CIF_ID VARCHAR2(36 CHAR) NOT NULL,
  FUNDING_ACCOUNT_ID NUMBER(19) NOT NULL REFERENCES M04_BANK_ACCOUNT(ACCOUNT_ID),
  PRODUCT_ID NUMBER(19) NOT NULL REFERENCES M03_PM_PRODUCT(PRODUCT_ID),
  PRODUCT_VERSION_ID NUMBER(19) NOT NULL REFERENCES M03_PM_PRODUCT_VERSION(PRODUCT_VERSION_ID),
  PRINCIPAL NUMBER(18,2) NOT NULL,
  TENURE_MONTHS NUMBER(4) NOT NULL,
  ANNUAL_RATE_PCT NUMBER(12,8) NOT NULL,
  DAY_COUNT_BASIS VARCHAR2(20 CHAR) NOT NULL,
  ROUNDING_MODE VARCHAR2(20 CHAR) NOT NULL,
  START_DATE DATE NOT NULL,
  MATURITY_DATE DATE NOT NULL,
  MATURITY_INTEREST NUMBER(18,2) NOT NULL,
  STATUS VARCHAR2(12 CHAR) DEFAULT 'ACTIVE' NOT NULL,
  FUNDING_JOURNAL_ID NUMBER(19) NOT NULL REFERENCES M05_GL_JOURNAL(JOURNAL_ID),
  PRINCIPAL_JOURNAL_ID NUMBER(19) REFERENCES M05_GL_JOURNAL(JOURNAL_ID),
  INTEREST_JOURNAL_ID NUMBER(19) REFERENCES M05_GL_JOURNAL(JOURNAL_ID),
  CREATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  MATURED_AT TIMESTAMP(6) WITH TIME ZONE,
  CONSTRAINT MBX_TERM_AMOUNT CHECK (PRINCIPAL>0 AND TENURE_MONTHS>0 AND MATURITY_INTEREST>=0),
  CONSTRAINT MBX_TERM_DATES CHECK (MATURITY_DATE>START_DATE),
  CONSTRAINT MBX_TERM_STATUS CHECK (STATUS IN ('ACTIVE','MATURED'))
);
CREATE INDEX MBX_TERM_DEPOSIT_DUE ON MBX_TERM_DEPOSIT(STATUS,MATURITY_DATE);
CREATE INDEX MBX_TERM_DEPOSIT_CIF ON MBX_TERM_DEPOSIT(PRIMARY_CIF_ID,TERM_DEPOSIT_ID);

MERGE INTO M05_GL_ACCOUNT g USING (
  SELECT 'MBX_DEPOSIT_INTEREST_EXPENSE' code,'Customer deposit interest expense' gl_name,'EXPENSE' account_class,'DR' normal_side FROM DUAL
  UNION ALL SELECT 'MBX_TERM_DEPOSIT_LIABILITY','Fixed deposit principal liability','LIABILITY','CR' FROM DUAL
) s ON (g.GL_CODE=s.code)
WHEN NOT MATCHED THEN INSERT (GL_CODE,GL_NAME,ACCOUNT_CLASS,NORMAL_SIDE,CURRENCY_CODE,ACTIVE_FLAG)
VALUES (s.code,s.gl_name,s.account_class,s.normal_side,'INR','Y');

-- Existing active savings versions inherit the same customer-liability GL used for cash deposits.
MERGE INTO M05_GL_PRODUCT_MAPPING m USING (
  SELECT DISTINCT v.PRODUCT_VERSION_ID,d.GL_ACCOUNT_ID
    FROM M03_PM_PRODUCT p JOIN M03_PM_PRODUCT_VERSION v ON v.PRODUCT_ID=p.PRODUCT_ID
    JOIN M05_GL_PRODUCT_MAPPING d ON d.PRODUCT_VERSION_ID=v.PRODUCT_VERSION_ID
   WHERE p.PRODUCT_TYPE='SAVINGS' AND v.VERSION_STATE='ACTIVE'
     AND d.POSTING_TYPE='DEPOSIT' AND d.GL_ROLE_CODE='CUSTOMER_LIABILITY'
     AND d.STATUS='ACTIVE' AND d.EFFECTIVE_FROM<=SYSDATE
     AND (d.EFFECTIVE_TO IS NULL OR d.EFFECTIVE_TO>=SYSDATE)
) s ON (m.PRODUCT_VERSION_ID=s.PRODUCT_VERSION_ID AND m.POSTING_TYPE='INTEREST'
        AND m.GL_ROLE_CODE='CUSTOMER_LIABILITY' AND m.STATUS='ACTIVE')
WHEN NOT MATCHED THEN INSERT (PRODUCT_VERSION_ID,POSTING_TYPE,GL_ROLE_CODE,GL_ACCOUNT_ID,EFFECTIVE_FROM,CREATED_BY)
VALUES (s.PRODUCT_VERSION_ID,'INTEREST','CUSTOMER_LIABILITY',s.GL_ACCOUNT_ID,TRUNC(SYSDATE),'DEPOSIT_INTEREST_MIGRATION');

MERGE INTO M05_GL_PRODUCT_MAPPING m USING (
  SELECT v.PRODUCT_VERSION_ID,g.GL_ACCOUNT_ID
    FROM M03_PM_PRODUCT p JOIN M03_PM_PRODUCT_VERSION v ON v.PRODUCT_ID=p.PRODUCT_ID
    CROSS JOIN M05_GL_ACCOUNT g
   WHERE p.PRODUCT_TYPE='SAVINGS' AND v.VERSION_STATE='ACTIVE'
     AND g.GL_CODE='MBX_DEPOSIT_INTEREST_EXPENSE' AND g.ACTIVE_FLAG='Y'
) s ON (m.PRODUCT_VERSION_ID=s.PRODUCT_VERSION_ID AND m.POSTING_TYPE='INTEREST'
        AND m.GL_ROLE_CODE='INTEREST_EXPENSE' AND m.STATUS='ACTIVE')
WHEN NOT MATCHED THEN INSERT (PRODUCT_VERSION_ID,POSTING_TYPE,GL_ROLE_CODE,GL_ACCOUNT_ID,EFFECTIVE_FROM,CREATED_BY)
VALUES (s.PRODUCT_VERSION_ID,'INTEREST','INTEREST_EXPENSE',s.GL_ACCOUNT_ID,TRUNC(SYSDATE),'DEPOSIT_INTEREST_MIGRATION');

-- Term deposits use a separate principal liability. New deposit versions must be mapped at approval.
MERGE INTO M05_GL_PRODUCT_MAPPING m USING (
  SELECT v.PRODUCT_VERSION_ID,r.GL_ROLE_CODE,g.GL_ACCOUNT_ID
    FROM M03_PM_PRODUCT p JOIN M03_PM_PRODUCT_VERSION v ON v.PRODUCT_ID=p.PRODUCT_ID
    CROSS JOIN (
      SELECT 'TERM_LIABILITY' GL_ROLE_CODE,'MBX_TERM_DEPOSIT_LIABILITY' GL_CODE FROM DUAL
      UNION ALL SELECT 'INTEREST_EXPENSE','MBX_DEPOSIT_INTEREST_EXPENSE' FROM DUAL
    ) r JOIN M05_GL_ACCOUNT g ON g.GL_CODE=r.GL_CODE AND g.ACTIVE_FLAG='Y'
   WHERE p.PRODUCT_TYPE='DEPOSIT' AND v.VERSION_STATE='ACTIVE'
) s ON (m.PRODUCT_VERSION_ID=s.PRODUCT_VERSION_ID AND m.POSTING_TYPE='TERM_DEPOSIT'
        AND m.GL_ROLE_CODE=s.GL_ROLE_CODE AND m.STATUS='ACTIVE')
WHEN NOT MATCHED THEN INSERT (PRODUCT_VERSION_ID,POSTING_TYPE,GL_ROLE_CODE,GL_ACCOUNT_ID,EFFECTIVE_FROM,CREATED_BY)
VALUES (s.PRODUCT_VERSION_ID,'TERM_DEPOSIT',s.GL_ROLE_CODE,s.GL_ACCOUNT_ID,TRUNC(SYSDATE),'DEPOSIT_INTEREST_MIGRATION');

COMMIT;
