-- Oracle demo IAM alignment. Run as schema owner after migrations 010 and 015-022.
-- Every existing username, user status, password, CIF and account is retained.
-- The confirmed adipil customer supplies CUSTOMER product scopes only.
SET DEFINE OFF
SET SERVEROUTPUT ON
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

DECLARE
  TYPE codes IS TABLE OF VARCHAR2(100);
  customer_codes codes := codes(
    'ACCOUNT_READ','TXN_READ','TXN_POST','PAYMENT_READ','PAYMENT_CREATE','STATEMENT_READ',
    'PRIVACY_CONSENT_SELF','PRIVACY_CONSENT_VIEW','FX_READ','LOAN_READ','LOAN_APPLY',
    'LOAN_ACCEPT','CIF_READ','PRODUCT_READ','CC_READ','CC_APPLY','CC_MANAGE','CC_SPEND','CC_REPAY');
  checker_codes codes := codes(
    'CC_READ','CC_APPROVE','CC_PRODUCT_APPROVE','SYSTEM_SCHEMA_READ','IAM_USER_READ','IAM_AUDIT_READ','CIF_READ',
    'PRODUCT_READ','ACCOUNT_READ','TXN_READ','GL_READ','GL_RECONCILE','PAYMENT_READ','TREASURY_READ','LOAN_READ',
    'STATEMENT_READ','STATEMENT_CATALOG_READ','PRIVACY_PURPOSE_VIEW','PRIVACY_CONSENT_VIEW','PRIVACY_CASE_VIEW',
    'PRIVACY_HOLD_VIEW','PRIVACY_POLICY_VIEW','PRIVACY_AUDIT_VIEW','PRIVACY_EXPORT_VIEW','FX_READ','TELLER_READ',
    'IAM_ACCESS_APPROVE','KYC_REVIEW','PRODUCT_APPROVE','ACCOUNT_APPROVE','TXN_REVERSE_APPROVE','GL_CLOSE_APPROVE',
    'PAYMENT_APPROVE','TREASURY_WORK_APPROVE','LOAN_DECIDE','LOAN_DOCUMENT_VERIFY','LOAN_DISBURSE_APPROVE',
    'TELLER_APPROVE','FX_APPROVE','BENEFICIARY_VERIFY','PRIVACY_PURPOSE_APPROVE','PRIVACY_HOLD_APPROVE',
    'PRIVACY_EXPORT_APPROVE','STATEMENT_APPROVE');
  admin_id VARCHAR2(36); checker_id VARCHAR2(36); customer_id VARCHAR2(36);
  admin_role VARCHAR2(36); checker_role VARCHAR2(36); customer_role VARCHAR2(36);
  reference_assignment VARCHAR2(36);
  scope_dimensions codes; scope_values codes;
  n NUMBER; permission_id VARCHAR2(36); run_id VARCHAR2(36):=LOWER(RAWTOHEX(SYS_GUID()));

  FUNCTION role_for(code VARCHAR2, title VARCHAR2, sensitive VARCHAR2) RETURN VARCHAR2 IS rid VARCHAR2(36);
  BEGIN
    MERGE INTO M01_IAM_ROLE r USING (SELECT code role_code FROM dual) s ON (r.ROLE_CODE=s.role_code)
    WHEN MATCHED THEN UPDATE SET r.STATUS='ACTIVE',r.DISPLAY_NAME=title,r.SENSITIVE_FLAG=sensitive
    WHEN NOT MATCHED THEN INSERT (ROLE_ID,ROLE_CODE,DISPLAY_NAME,STATUS,SENSITIVE_FLAG)
      VALUES (LOWER(RAWTOHEX(SYS_GUID())),code,title,'ACTIVE',sensitive);
    SELECT ROLE_ID INTO rid FROM M01_IAM_ROLE WHERE ROLE_CODE=code;
    RETURN rid;
  END;
  PROCEDURE grant_exact(rid VARCHAR2, allowed codes) IS
  BEGIN
    DELETE FROM M01_IAM_ROLE_PERMISSION WHERE ROLE_ID=rid;
    FOR i IN 1..allowed.COUNT LOOP
      SELECT PERMISSION_ID INTO permission_id FROM M01_IAM_PERMISSION WHERE PERMISSION_CODE=allowed(i);
      INSERT INTO M01_IAM_ROLE_PERMISSION (ROLE_ID,PERMISSION_ID) VALUES (rid,permission_id);
    END LOOP;
  END;
  PROCEDURE assign_only(uid VARCHAR2,rid VARCHAR2,scope VARCHAR2) IS
  BEGIN
    UPDATE M01_IAM_USER_ROLE SET STATUS='REVOKED',VALID_TO=CASE WHEN VALID_FROM>=SYSTIMESTAMP THEN VALID_FROM+NUMTODSINTERVAL(1,'SECOND') ELSE SYSTIMESTAMP END
      WHERE USER_ID=uid AND STATUS='ACTIVE'
        AND NOT (ROLE_ID=rid AND SCOPE_TYPE=scope AND SCOPE_REF IS NULL AND VALID_FROM<=SYSTIMESTAMP AND VALID_TO IS NULL);
    SELECT COUNT(*) INTO n FROM M01_IAM_USER_ROLE
      WHERE USER_ID=uid AND ROLE_ID=rid AND STATUS='ACTIVE' AND SCOPE_TYPE=scope
        AND SCOPE_REF IS NULL AND VALID_FROM<=SYSTIMESTAMP AND VALID_TO IS NULL;
    IF n=0 THEN
      INSERT INTO M01_IAM_USER_ROLE (ASSIGNMENT_ID,USER_ID,ROLE_ID,SCOPE_TYPE,STATUS,VALID_FROM)
        VALUES (LOWER(RAWTOHEX(SYS_GUID())),uid,rid,scope,'ACTIVE',SYSTIMESTAMP);
    END IF;
  END;
BEGIN
  -- All preflight checks precede writes; failure rolls the whole IAM transaction back.
  SELECT COUNT(*) INTO n FROM M01_IAM_USER WHERE LOWER(USERNAME)='adipil' AND USER_TYPE='CUSTOMER' AND STATUS='ACTIVE';
  IF n<>1 THEN RAISE_APPLICATION_ERROR(-20091,'Expected one active adipil customer; verify the existing username first.'); END IF;
  SELECT USER_ID INTO customer_id FROM M01_IAM_USER WHERE LOWER(USERNAME)='adipil' AND USER_TYPE='CUSTOMER' AND STATUS='ACTIVE';
  SELECT USER_ID INTO admin_id FROM M01_IAM_USER WHERE LOWER(USERNAME)='admin' AND USER_TYPE='EMPLOYEE' AND STATUS='ACTIVE';
  SELECT USER_ID INTO checker_id FROM M01_IAM_USER WHERE LOWER(USERNAME)='checker1' AND USER_TYPE='EMPLOYEE' AND STATUS='ACTIVE';
  IF admin_id=checker_id THEN RAISE_APPLICATION_ERROR(-20092,'Admin and checker must be different identities.'); END IF;
  SELECT COUNT(*) INTO n FROM M01_IAM_CUSTOMER_LINK WHERE USER_ID=customer_id AND STATUS='ACTIVE'
    AND VALID_FROM<=SYSTIMESTAMP AND (VALID_TO IS NULL OR VALID_TO>SYSTIMESTAMP);
  IF n=0 THEN RAISE_APPLICATION_ERROR(-20093,'The customer reference needs an active CIF link.'); END IF;
  SELECT COUNT(*) INTO n FROM M01_IAM_USER_ROLE a JOIN M01_IAM_ROLE r ON r.ROLE_ID=a.ROLE_ID
    WHERE a.USER_ID=customer_id AND a.STATUS='ACTIVE' AND r.STATUS='ACTIVE' AND a.SCOPE_TYPE='SELF'
      AND a.VALID_FROM<=SYSTIMESTAMP AND (a.VALID_TO IS NULL OR a.VALID_TO>SYSTIMESTAMP);
  IF n<>1 THEN RAISE_APPLICATION_ERROR(-20095,'Expected one active SELF customer assignment on adipil; review the reference grants first.'); END IF;
  SELECT a.ASSIGNMENT_ID INTO reference_assignment FROM M01_IAM_USER_ROLE a JOIN M01_IAM_ROLE r ON r.ROLE_ID=a.ROLE_ID
    WHERE a.USER_ID=customer_id AND a.STATUS='ACTIVE' AND r.STATUS='ACTIVE' AND a.SCOPE_TYPE='SELF'
      AND a.VALID_FROM<=SYSTIMESTAMP AND (a.VALID_TO IS NULL OR a.VALID_TO>SYSTIMESTAMP);
  SELECT DIMENSION_CODE,SCOPE_VALUE BULK COLLECT INTO scope_dimensions,scope_values
    FROM M01_IAM_USER_ROLE_SCOPE WHERE ASSIGNMENT_ID=reference_assignment;
  FOR i IN 1..customer_codes.COUNT LOOP
    SELECT COUNT(*) INTO n FROM M01_IAM_PERMISSION WHERE PERMISSION_CODE=customer_codes(i);
    IF n<>1 THEN RAISE_APPLICATION_ERROR(-20094,'Install missing permission: '||customer_codes(i)); END IF;
  END LOOP;
  FOR i IN 1..checker_codes.COUNT LOOP
    SELECT COUNT(*) INTO n FROM M01_IAM_PERMISSION WHERE PERMISSION_CODE=checker_codes(i);
    IF n<>1 THEN RAISE_APPLICATION_ERROR(-20094,'Install missing permission: '||checker_codes(i)); END IF;
  END LOOP;

  admin_role:=role_for('BANK_ADMIN','Bank admin','Y');
  checker_role:=role_for('BANK_CHECKER','Bank checker','Y');
  customer_role:=role_for('BANK_CUSTOMER','Customer','N');
  grant_exact(customer_role,customer_codes); grant_exact(checker_role,checker_codes);
  INSERT INTO M01_IAM_ROLE_PERMISSION (ROLE_ID,PERMISSION_ID)
    SELECT admin_role,p.PERMISSION_ID FROM M01_IAM_PERMISSION p WHERE NOT EXISTS
      (SELECT 1 FROM M01_IAM_ROLE_PERMISSION rp WHERE rp.ROLE_ID=admin_role AND rp.PERMISSION_ID=p.PERMISSION_ID);
  assign_only(admin_id,admin_role,'GLOBAL'); assign_only(checker_id,checker_role,'GLOBAL');
  DELETE FROM M01_IAM_USER_ROLE_SCOPE WHERE ASSIGNMENT_ID IN
    (SELECT ASSIGNMENT_ID FROM M01_IAM_USER_ROLE WHERE USER_ID IN (admin_id,checker_id) AND STATUS='ACTIVE');
  -- Customer IAM product/currency dimensions match the reference exactly; identity status is unchanged.
  FOR u IN (SELECT USER_ID FROM M01_IAM_USER WHERE USER_TYPE='CUSTOMER' AND STATUS<>'CLOSED') LOOP
    assign_only(u.USER_ID,customer_role,'SELF');
    FOR a IN (SELECT ASSIGNMENT_ID FROM M01_IAM_USER_ROLE WHERE USER_ID=u.USER_ID AND ROLE_ID=customer_role AND STATUS='ACTIVE') LOOP
      DELETE FROM M01_IAM_USER_ROLE_SCOPE WHERE ASSIGNMENT_ID=a.ASSIGNMENT_ID;
      FOR i IN 1..scope_dimensions.COUNT LOOP
        INSERT INTO M01_IAM_USER_ROLE_SCOPE (ASSIGNMENT_ID,DIMENSION_CODE,SCOPE_VALUE)
          VALUES (a.ASSIGNMENT_ID,scope_dimensions(i),scope_values(i));
      END LOOP;
    END LOOP;
  END LOOP;
  -- Existing checker demo identities also use the complete independent checker role.
  FOR u IN (SELECT USER_ID FROM M01_IAM_USER WHERE USER_TYPE='EMPLOYEE' AND LOWER(USERNAME) IN ('checker','mcp_demo_checker')) LOOP
    assign_only(u.USER_ID,checker_role,'GLOBAL');
    DELETE FROM M01_IAM_USER_ROLE_SCOPE WHERE ASSIGNMENT_ID IN
      (SELECT ASSIGNMENT_ID FROM M01_IAM_USER_ROLE WHERE USER_ID=u.USER_ID AND ROLE_ID=checker_role AND STATUS='ACTIVE');
  END LOOP;
  -- Demo authority ceilings are explicit. Existing higher/lower configured active ceilings are retained.
  FOR a IN (SELECT 'LOAN_SANCTION' code,5000000 amount,20 rate FROM dual
            UNION ALL SELECT 'CC_LIMIT',200000,24 FROM dual) LOOP
    INSERT INTO M01_IAM_ROLE_AUTHORITY (AUTHORITY_ID,ROLE_ID,AUTHORITY_CODE,CURRENCY_CODE,MAX_AMOUNT,MAX_RATE_PCT,VALID_FROM)
      SELECT LOWER(RAWTOHEX(SYS_GUID())),checker_role,a.code,'INR',a.amount,a.rate,SYSTIMESTAMP FROM dual
      WHERE NOT EXISTS (SELECT 1 FROM M01_IAM_ROLE_AUTHORITY x WHERE x.ROLE_ID=checker_role AND x.AUTHORITY_CODE=a.code
        AND x.CURRENCY_CODE IN ('INR','*') AND x.MAX_AMOUNT IS NOT NULL AND x.MAX_RATE_PCT IS NOT NULL
        AND x.VALID_FROM<=SYSTIMESTAMP AND (x.VALID_TO IS NULL OR x.VALID_TO>SYSTIMESTAMP));
  END LOOP;
  -- Entitlement changes revoke prior login sessions and refresh identity versions.
  UPDATE M01_IAM_USER SET ENTITLEMENT_VERSION=ENTITLEMENT_VERSION+1,ROW_VERSION=ROW_VERSION+1,UPDATED_AT=SYSTIMESTAMP
    WHERE USER_TYPE='CUSTOMER' OR USER_ID IN (admin_id,checker_id) OR LOWER(USERNAME) IN ('mcp_demo_checker','checker');
  UPDATE M01_IAM_SESSION SET STATUS='REVOKED' WHERE STATUS='ACTIVE' AND USER_ID IN
    (SELECT USER_ID FROM M01_IAM_USER WHERE USER_TYPE='CUSTOMER' OR USER_ID IN (admin_id,checker_id)
      OR LOWER(USERNAME) IN ('mcp_demo_checker','checker'));
  INSERT INTO M01_IAM_AUDIT_EVENT (AUDIT_ID,EVENT_TYPE,RESOURCE_TYPE,RESOURCE_ID,RESULT,REASON_CODE,CORRELATION_ID)
    VALUES (LOWER(RAWTOHEX(SYS_GUID())),'DEMO_ROLES_UNIFIED','IAM_ROLE',customer_role,'SUCCESS','CUSTOMER_REFERENCE_ALIGNMENT',run_id);
  DBMS_OUTPUT.PUT_LINE('Users retained. Customers share adipil product scopes; admin is maker; checker1 is the primary independent checker. Sign in again.');
END;
/
COMMIT;

SELECT u.USERNAME,u.USER_TYPE,u.STATUS,r.ROLE_CODE,a.SCOPE_TYPE
  FROM M01_IAM_USER u JOIN M01_IAM_USER_ROLE a ON a.USER_ID=u.USER_ID JOIN M01_IAM_ROLE r ON r.ROLE_ID=a.ROLE_ID
  WHERE LOWER(u.USERNAME) IN ('adipil','admin','checker1') AND a.STATUS='ACTIVE' ORDER BY u.USERNAME;
