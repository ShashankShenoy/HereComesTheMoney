-- One salted payment PIN per customer. Existing customers enroll after sign-in.
CREATE TABLE MBX_PAYMENT_PIN (
 USER_ID VARCHAR2(36) PRIMARY KEY REFERENCES M01_IAM_USER(USER_ID),
 PIN_HASH VARCHAR2(100) NOT NULL,
 FAILED_ATTEMPTS NUMBER(10) DEFAULT 0 NOT NULL,
 LOCKED_UNTIL TIMESTAMP(6) WITH TIME ZONE,
 RESET_FAILED_ATTEMPTS NUMBER(10) DEFAULT 0 NOT NULL,
 RESET_LOCKED_UNTIL TIMESTAMP(6) WITH TIME ZONE,
 CHANGED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
 CONSTRAINT MBX_PAYMENT_PIN_ATTEMPTS CHECK (FAILED_ATTEMPTS BETWEEN 0 AND 5 AND RESET_FAILED_ATTEMPTS BETWEEN 0 AND 5)
);
