-- Install module permissions and ledger codes without changing user assignments.
DECLARE
  TYPE codes IS TABLE OF VARCHAR2(100);
  v_codes codes := codes('CC_READ','CC_PRODUCT_MANAGE','CC_PRODUCT_APPROVE','CC_APPLY','CC_APPROVE','CC_MANAGE','CC_SPEND','CC_REPAY','CC_SERVICE');
BEGIN
  FOR i IN 1..v_codes.COUNT LOOP
    MERGE INTO M01_IAM_PERMISSION p USING (SELECT v_codes(i) code FROM dual) s ON (p.PERMISSION_CODE=s.code)
    WHEN NOT MATCHED THEN INSERT(PERMISSION_ID,PERMISSION_CODE,RESOURCE_CODE,ACTION_CODE)
      VALUES(LOWER(RAWTOHEX(SYS_GUID())),s.code,'CREDIT_CARD',s.code);
  END LOOP;
  INSERT INTO M01_IAM_ROLE_PERMISSION(ROLE_ID,PERMISSION_ID)
  SELECT r.ROLE_ID,p.PERMISSION_ID FROM M01_IAM_ROLE r CROSS JOIN M01_IAM_PERMISSION p
  WHERE ((r.ROLE_CODE='BANK_ADMIN' AND p.PERMISSION_CODE LIKE 'CC_%')
      OR (r.ROLE_CODE='BANK_CHECKER' AND p.PERMISSION_CODE IN ('CC_READ','CC_APPROVE','CC_PRODUCT_APPROVE'))
      OR (r.ROLE_CODE='RETAIL_CUSTOMER' AND p.PERMISSION_CODE IN ('CC_READ','CC_APPLY','CC_MANAGE','CC_SPEND','CC_REPAY')))
    AND NOT EXISTS(SELECT 1 FROM M01_IAM_ROLE_PERMISSION x WHERE x.ROLE_ID=r.ROLE_ID AND x.PERMISSION_ID=p.PERMISSION_ID);
  -- Entitlement refresh on next request; existing sessions must sign in again.
  UPDATE M01_IAM_USER SET ENTITLEMENT_VERSION=ENTITLEMENT_VERSION+1
    WHERE USER_ID IN (SELECT a.USER_ID FROM M01_IAM_USER_ROLE a JOIN M01_IAM_ROLE r ON r.ROLE_ID=a.ROLE_ID
      WHERE r.ROLE_CODE IN ('BANK_ADMIN','BANK_CHECKER','RETAIL_CUSTOMER'));
  FOR g IN (SELECT 'CC_RECEIVABLE' code,'Credit card receivables' label,'ASSET' class,'DR' side FROM dual
    UNION ALL SELECT 'CC_SETTLEMENT','Simulated card merchant settlement','LIABILITY','CR' FROM dual
    UNION ALL SELECT 'CC_INTEREST','Credit card interest income','INCOME','CR' FROM dual) LOOP
    INSERT INTO M05_GL_ACCOUNT(GL_CODE,GL_NAME,ACCOUNT_CLASS,NORMAL_SIDE)
      SELECT g.code,g.label,g.class,g.side FROM dual WHERE NOT EXISTS(SELECT 1 FROM M05_GL_ACCOUNT WHERE GL_CODE=g.code);
  END LOOP;
END;
