CREATE OR REPLACE TRIGGER CC_PRODUCT_TERMS_IMMUTABLE
BEFORE UPDATE OR DELETE ON M11_CC_PRODUCT
BEGIN
  IF DELETING OR UPDATING('PRODUCT_ID') OR UPDATING('PRODUCT_CODE') OR UPDATING('PRODUCT_NAME')
    OR UPDATING('VERSION_NO') OR UPDATING('CURRENCY_CODE') OR UPDATING('MINIMUM_LIMIT')
    OR UPDATING('MAXIMUM_LIMIT') OR UPDATING('ANNUAL_RATE_PCT') OR UPDATING('MIN_PAYMENT_PCT')
    OR UPDATING('MIN_PAYMENT_FLOOR') OR UPDATING('BILLING_DAY') OR UPDATING('PAYMENT_DUE_DAYS')
    OR UPDATING('DESCRIPTION') OR UPDATING('MAKER_ID') THEN
    RAISE_APPLICATION_ERROR(-20060,'Credit card terms are immutable; create a new product version.');
  END IF;
END;
