CREATE TABLE M11_CC_PRODUCT (
  PRODUCT_ID VARCHAR2(36 CHAR) PRIMARY KEY,
  PRODUCT_CODE VARCHAR2(30 CHAR) NOT NULL,
  PRODUCT_NAME VARCHAR2(120 CHAR) NOT NULL,
  VERSION_NO NUMBER(10) NOT NULL,
  STATUS VARCHAR2(12 CHAR) DEFAULT 'PENDING' NOT NULL,
  CURRENCY_CODE CHAR(3 CHAR) DEFAULT 'INR' NOT NULL,
  MINIMUM_LIMIT NUMBER(18,2) NOT NULL,
  MAXIMUM_LIMIT NUMBER(18,2) NOT NULL,
  ANNUAL_RATE_PCT NUMBER(5,2) NOT NULL,
  MIN_PAYMENT_PCT NUMBER(5,2) NOT NULL,
  MIN_PAYMENT_FLOOR NUMBER(18,2) NOT NULL,
  BILLING_DAY NUMBER(2) NOT NULL,
  PAYMENT_DUE_DAYS NUMBER(2) NOT NULL,
  DESCRIPTION VARCHAR2(1000 CHAR) NOT NULL,
  MAKER_ID VARCHAR2(36 CHAR) NOT NULL REFERENCES M01_IAM_USER(USER_ID),
  CHECKER_ID VARCHAR2(36 CHAR) REFERENCES M01_IAM_USER(USER_ID),
  DECISION_REASON VARCHAR2(500 CHAR),
  CREATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  DECIDED_AT TIMESTAMP(6) WITH TIME ZONE,
  ROW_VERSION NUMBER(19) DEFAULT 1 NOT NULL,
  CONSTRAINT CC_PRODUCT_VERSION_UK UNIQUE(PRODUCT_CODE,VERSION_NO),
  CONSTRAINT CC_PRODUCT_STATUS_CK CHECK(STATUS IN ('PENDING','APPROVED','REJECTED','RETIRED')),
  CONSTRAINT CC_PRODUCT_LIMIT_CK CHECK(MINIMUM_LIMIT>=1000 AND MAXIMUM_LIMIT>=MINIMUM_LIMIT AND MAXIMUM_LIMIT<=10000000),
  CONSTRAINT CC_PRODUCT_TERMS_CK CHECK(ANNUAL_RATE_PCT BETWEEN 0 AND 48 AND MIN_PAYMENT_PCT BETWEEN 1 AND 100 AND MIN_PAYMENT_FLOOR>=0 AND BILLING_DAY BETWEEN 1 AND 28 AND PAYMENT_DUE_DAYS BETWEEN 7 AND 25 AND CURRENCY_CODE='INR' AND VERSION_NO>=1),
  CONSTRAINT CC_PRODUCT_CHECKER_CK CHECK((CHECKER_ID IS NULL OR CHECKER_ID<>MAKER_ID) AND (STATUS='PENDING' OR CHECKER_ID IS NOT NULL))
);

CREATE TABLE M11_CC_APPLICATION (
  APPLICATION_ID VARCHAR2(36 CHAR) PRIMARY KEY,
  PRODUCT_ID VARCHAR2(36 CHAR) NOT NULL REFERENCES M11_CC_PRODUCT(PRODUCT_ID),
  CIF_ID VARCHAR2(36 CHAR) NOT NULL REFERENCES M02_CIF_CUSTOMER(CIF_ID),
  BRANCH_CODE VARCHAR2(40 CHAR) NOT NULL,
  REPAYMENT_ACCOUNT_ID NUMBER(19) NOT NULL REFERENCES M04_BANK_ACCOUNT(ACCOUNT_ID),
  REQUESTED_LIMIT NUMBER(18,2) NOT NULL,
  APPROVED_LIMIT NUMBER(18,2),
  STATUS VARCHAR2(12 CHAR) DEFAULT 'PENDING' NOT NULL,
  TERMS_ACCEPTED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  MAKER_ID VARCHAR2(36 CHAR) NOT NULL REFERENCES M01_IAM_USER(USER_ID),
  CHECKER_ID VARCHAR2(36 CHAR) REFERENCES M01_IAM_USER(USER_ID),
  DECISION_REASON VARCHAR2(500 CHAR),
  CREATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  DECIDED_AT TIMESTAMP(6) WITH TIME ZONE,
  ROW_VERSION NUMBER(19) DEFAULT 1 NOT NULL,
  CONSTRAINT CC_APPLICATION_STATUS_CK CHECK(STATUS IN ('PENDING','APPROVED','REJECTED','CANCELLED')),
  CONSTRAINT CC_APPLICATION_LIMIT_CK CHECK(REQUESTED_LIMIT>=1000 AND (APPROVED_LIMIT IS NULL OR (APPROVED_LIMIT>=1000 AND APPROVED_LIMIT<=REQUESTED_LIMIT))),
  CONSTRAINT CC_APPLICATION_CHECKER_CK CHECK((CHECKER_ID IS NULL OR CHECKER_ID<>MAKER_ID) AND (STATUS NOT IN ('APPROVED','REJECTED') OR CHECKER_ID IS NOT NULL) AND (STATUS<>'APPROVED' OR APPROVED_LIMIT IS NOT NULL))
);
CREATE INDEX CC_APPLICATION_CIF_IX ON M11_CC_APPLICATION(CIF_ID,STATUS);

CREATE TABLE M11_CC_CARD (
  CARD_ID VARCHAR2(36 CHAR) PRIMARY KEY,
  APPLICATION_ID VARCHAR2(36 CHAR) NOT NULL UNIQUE REFERENCES M11_CC_APPLICATION(APPLICATION_ID),
  PRODUCT_ID VARCHAR2(36 CHAR) NOT NULL REFERENCES M11_CC_PRODUCT(PRODUCT_ID),
  CIF_ID VARCHAR2(36 CHAR) NOT NULL REFERENCES M02_CIF_CUSTOMER(CIF_ID),
  BRANCH_CODE VARCHAR2(40 CHAR) NOT NULL,
  REPAYMENT_ACCOUNT_ID NUMBER(19) NOT NULL REFERENCES M04_BANK_ACCOUNT(ACCOUNT_ID),
  CARD_REFERENCE VARCHAR2(45 CHAR) NOT NULL UNIQUE,
  DISPLAY_ENDING CHAR(4 CHAR) NOT NULL,
  STATUS VARCHAR2(10 CHAR) DEFAULT 'ISSUED' NOT NULL,
  CREDIT_LIMIT NUMBER(18,2) NOT NULL,
  PRINCIPAL_BALANCE NUMBER(18,2) DEFAULT 0 NOT NULL,
  INTEREST_BALANCE NUMBER(18,2) DEFAULT 0 NOT NULL,
  ACCRUED_INTEREST NUMBER(24,8) DEFAULT 0 NOT NULL,
  LAST_ACCRUAL_DATE DATE NOT NULL,
  NEXT_STATEMENT_DATE DATE NOT NULL,
  LAST_STATEMENT_ENTRY NUMBER(19) DEFAULT 0 NOT NULL,
  ISSUED_DATE DATE NOT NULL,
  EXPIRY_DATE DATE NOT NULL,
  ROW_VERSION NUMBER(19) DEFAULT 1 NOT NULL,
  CONSTRAINT CC_CARD_STATUS_CK CHECK(STATUS IN ('ISSUED','ACTIVE','FROZEN','BLOCKED','CLOSED')),
  CONSTRAINT CC_CARD_BALANCE_CK CHECK(CREDIT_LIMIT>=1000 AND PRINCIPAL_BALANCE>=0 AND INTEREST_BALANCE>=0 AND ACCRUED_INTEREST>=-0.005),
  CONSTRAINT CC_CARD_DATES_CK CHECK(EXPIRY_DATE>ISSUED_DATE AND LAST_ACCRUAL_DATE>=ISSUED_DATE)
);
CREATE INDEX CC_CARD_CIF_IX ON M11_CC_CARD(CIF_ID,STATUS);
CREATE INDEX CC_CARD_ACCOUNT_IX ON M11_CC_CARD(REPAYMENT_ACCOUNT_ID,STATUS);

CREATE TABLE M11_CC_ENTRY (
  ENTRY_ID NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  CARD_ID VARCHAR2(36 CHAR) NOT NULL REFERENCES M11_CC_CARD(CARD_ID),
  ENTRY_TYPE VARCHAR2(12 CHAR) NOT NULL,
  AMOUNT NUMBER(18,2) NOT NULL,
  PRINCIPAL_DELTA NUMBER(18,2) NOT NULL,
  INTEREST_DELTA NUMBER(18,2) NOT NULL,
  DEPOSIT_CREDIT NUMBER(18,2) DEFAULT 0 NOT NULL,
  PRINCIPAL_AFTER NUMBER(18,2) NOT NULL,
  INTEREST_AFTER NUMBER(18,2) NOT NULL,
  DESCRIPTION VARCHAR2(500 CHAR) NOT NULL,
  BUSINESS_DATE DATE NOT NULL,
  TXN_ID NUMBER(19) NOT NULL UNIQUE REFERENCES M05_TXN_TRANSACTION_LOG(TXN_ID),
  JOURNAL_ID NUMBER(19) NOT NULL UNIQUE REFERENCES M05_GL_JOURNAL(JOURNAL_ID),
  REFUND_OF_ENTRY NUMBER(19) UNIQUE REFERENCES M11_CC_ENTRY(ENTRY_ID),
  ACTOR_ID VARCHAR2(36 CHAR) NOT NULL REFERENCES M01_IAM_USER(USER_ID),
  CREATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT CC_ENTRY_TYPE_CK CHECK(ENTRY_TYPE IN ('PURCHASE','REFUND','REPAYMENT','INTEREST')),
  CONSTRAINT CC_ENTRY_AMOUNT_CK CHECK(AMOUNT>0 AND PRINCIPAL_AFTER>=0 AND INTEREST_AFTER>=0 AND DEPOSIT_CREDIT>=0),
  CONSTRAINT CC_ENTRY_DELTA_CK CHECK(
    (ENTRY_TYPE='PURCHASE' AND PRINCIPAL_DELTA=AMOUNT AND INTEREST_DELTA=0 AND DEPOSIT_CREDIT=0 AND REFUND_OF_ENTRY IS NULL) OR
    (ENTRY_TYPE='INTEREST' AND INTEREST_DELTA=AMOUNT AND PRINCIPAL_DELTA=0 AND DEPOSIT_CREDIT=0 AND REFUND_OF_ENTRY IS NULL) OR
    (ENTRY_TYPE='REPAYMENT' AND PRINCIPAL_DELTA<=0 AND INTEREST_DELTA<=0 AND PRINCIPAL_DELTA+INTEREST_DELTA=-AMOUNT AND DEPOSIT_CREDIT=0 AND REFUND_OF_ENTRY IS NULL) OR
    (ENTRY_TYPE='REFUND' AND PRINCIPAL_DELTA<=0 AND INTEREST_DELTA=0 AND DEPOSIT_CREDIT-PRINCIPAL_DELTA=AMOUNT AND REFUND_OF_ENTRY IS NOT NULL))
);
CREATE INDEX CC_ENTRY_CARD_IX ON M11_CC_ENTRY(CARD_ID,ENTRY_ID);

